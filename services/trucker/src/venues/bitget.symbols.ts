/**
 * Every symbol bitget's download portal has ever known, spot and futures.
 *
 * **Versioned here rather than cached under `@meta/`, deliberately.** A ledger
 * is disposable: delete it and the next pass rebuilds it. This cannot be
 * rebuilt from anything trucker holds — a delisted symbol is absent from every
 * version of bitget's instruments API, while its files are still served, so the
 * archive is reachable only for as long as the *name* survives. Losing this
 * file loses history that no request can ask for again.
 *
 * Gathered from the portal's own symbol search, which is the one place the dead
 * ones appear:
 *
 *     POST https://www.bitget.com/v1/statistics/public/download/getSymbolList
 *     {"displaySymbol":"b","businessLine":1,"businessType":1,"languageType":0}
 *
 * A query matches on any substring and caps at 200 results, so the sweep walks
 * every prefix and refines those that hit the cap. That is a few hundred
 * requests against an undocumented endpoint — once, not on a schedule.
 *
 * The live instruments API stays the source for everything else: it carries
 * launch dates and it lists whatever is new. This supplies names only, and a
 * symbol present in both is the API's. New listings arrive through the API, so
 * this file only goes stale for symbols that both appeared *and* delisted since
 * it was made — re-sweep if trucker is ever stopped for that long.
 */

